// Prove the game is completable and report every dead end.
//
//   qe-solve <assets> [--emit-walkthrough FILE] [--dot FILE] [--allow-dead-ends]
//
// Exit code is non-zero if lint finds problems, the game can't be won, or any
// reachable state can no longer win (unless --allow-dead-ends).
#include <chrono>
#include <cstdio>
#include <fstream>
#include <string>

#include "core/solver.hpp"

using namespace qe;

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: qe-solve <assets> [--emit-walkthrough FILE] [--dot FILE] [--allow-dead-ends]\n");
        return 2;
    }
    std::string assets = argv[1], walkOut, dotOut;
    bool allowDead = false;
    for (int i = 2; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "--emit-walkthrough" && i + 1 < argc) walkOut = argv[++i];
        else if (a == "--dot" && i + 1 < argc) dotOut = argv[++i];
        else if (a == "--allow-dead-ends") allowDead = true;
    }
    try {
        auto content = loadContent(assets);
        DialogueLibrary lib(assets + "/" + content->inkJson);
        auto problems = lintContent(*content, lib);
        for (auto& p : problems) std::printf("lint: %s\n", p.c_str());

        auto t0 = std::chrono::steady_clock::now();
        SolveReport r = solve(*content, lib);
        double ms = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
        std::printf("%s: %zu reachable states, %zu transitions, %zu winning states (%.0f ms)\n",
                    content->title.c_str(), r.states, r.transitions, r.winStates, ms);
        std::printf("completable: %s\n", r.winnable ? "yes" : "NO");
        if (r.winnable) std::printf("shortest solution: %zu moves\n", r.shortestWin.size());
        std::printf("dead-end states: %zu (%zu ways in)\n", r.deadEndStates, r.deadEnds.size());
        for (auto& d : r.deadEnds) {
            std::printf("\nDEAD END after: %s\n  changed: %s\n  shortest way in:\n", d.lastMove.c_str(),
                        d.diff.c_str());
            for (auto& m : d.path) std::printf("    %s\n", m.c_str());
        }
        if (!walkOut.empty()) {
            std::ofstream f(walkOut, std::ios::binary);
            f << "# Shortest solution, generated by qe-solve. Replayed in CI by qe-headless --script.\n";
            for (auto& m : r.shortestWin) f << m << "\n";
        }
        if (!dotOut.empty()) std::ofstream(dotOut, std::ios::binary) << dependencyDot(*content);
        if (!problems.empty() || !r.winnable || (!allowDead && r.deadEndStates > 0)) return 1;
    } catch (const std::exception& e) {
        std::fprintf(stderr, "error: %s\n", e.what());
        return 1;
    }
    return 0;
}
